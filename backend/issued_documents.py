"""The documents the company owes the leaver, generated from the record.

Three of them have sat in `REQUIRED_DOCUMENTS` marked `issued: True` since the
beginning -- a relieving letter, an experience letter and a full-and-final
settlement statement -- and nothing ever produced one. The checklist tracked
them as "to be issued" forever, which is a to-do list nobody can action.

Two rules shape what is in them.

**Nothing is issued before the exit is actually finished.** A relieving letter
states that somebody has been released by the company. Handing one out while IT
clearance is open would make the letter a lie and the clearance pointless --
the letter is the thing the clearance exists to gate.

**No money is invented.** A settlement statement with figures this system has
never seen would be a fabricated financial record, and it would be believed:
it comes out as a PDF on company letterhead. So the statement reports what is
genuinely known -- which clearances passed, what was returned, what was written
off and therefore recoverable -- and says plainly that amounts come from
payroll. An honest statement of position is useful. An invented number is
worse than nothing.

No LLM anywhere in this module. These are legal records, and the same inputs
must produce the same document every time.
"""
from __future__ import annotations

import io
from datetime import date
from typing import Any

from reportlab.lib.enums import TA_JUSTIFY
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)
from reportlab.lib import colors

from .data_store import store
from .systems import asset_status

COMPANY = "Perficient"

#: id -> (filename stem, title). The ids match `REQUIRED_DOCUMENTS` so the
#: checklist and the download list cannot drift apart.
ISSUED = {
    "relieving-letter": ("Relieving letter", "Relieving Letter"),
    "experience-letter": ("Experience letter", "Experience Certificate"),
    "settlement-statement": ("Full-and-final settlement statement",
                             "Full and Final Settlement — Statement of Position"),
}

_INK = colors.HexColor("#0F2E2D")
_MUTED = colors.HexColor("#4A6866")
_LINE = colors.HexColor("#CDDCDB")


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle("t", parent=base["Title"], fontSize=15, leading=19,
                                textColor=_INK, spaceAfter=2),
        "sub": ParagraphStyle("s", parent=base["Normal"], fontSize=9, leading=12,
                              textColor=_MUTED),
        "body": ParagraphStyle("b", parent=base["Normal"], fontSize=10.5,
                               leading=16, textColor=_INK, alignment=TA_JUSTIFY,
                               spaceAfter=9),
        "small": ParagraphStyle("sm", parent=base["Normal"], fontSize=8.5,
                                leading=12, textColor=_MUTED),
    }


def _fmt(value: Any) -> str:
    if value is None or value == "":
        return "—"
    if isinstance(value, date):
        return value.strftime("%d %B %Y")
    return str(value)


def _facts_table(rows: list[tuple[str, Any]]) -> Table:
    t = Table([[k, _fmt(v)] for k, v in rows], colWidths=[52 * mm, 96 * mm])
    t.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("TEXTCOLOR", (0, 0), (0, -1), _MUTED),
        ("TEXTCOLOR", (1, 0), (1, -1), _INK),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("LINEBELOW", (0, 0), (-1, -2), 0.4, _LINE),
    ]))
    return t


def _render(title: str, subtitle: str, blocks: list[Any]) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=24 * mm, rightMargin=24 * mm,
        topMargin=22 * mm, bottomMargin=20 * mm,
        title=title, author=COMPANY,
    )
    st = _styles()
    story: list[Any] = [
        Paragraph(COMPANY, st["sub"]),
        Spacer(1, 7),
        Paragraph(title, st["title"]),
        Paragraph(subtitle, st["sub"]),
        Spacer(1, 16),
        *blocks,
        Spacer(1, 20),
        Paragraph(
            f"Generated by Offboard on {date.today().strftime('%d %B %Y')} from the "
            "exit record. No signature is required for it to be valid; the "
            "clearance record is the authority.", st["small"]),
    ]
    doc.build(story)
    return buf.getvalue()


def _context(case_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
    case = store.exit_case(case_id)
    if case is None:
        raise LookupError(f"Unknown exit case '{case_id}'.")
    employee = store.employee(str(case.meta.get("employee_id") or ""))
    return case.meta, (employee.meta if employee else {})


def readiness(case_id: str) -> dict[str, Any]:
    """Whether the leaving documents can be issued, and what is holding them.

    Every clearance, not most of them. The letter's whole content is "this
    person has been released", and a release with an open stage has not
    happened.
    """
    case_meta, _ = _context(case_id)
    stages = [s for s in (case_meta.get("stages") or []) if isinstance(s, dict)]
    outstanding = [str(s.get("name")) for s in stages
                   if str(s.get("status", "")).lower() != "completed"]
    return {
        "case_id": case_id,
        "ready": not outstanding and bool(stages),
        "outstanding": outstanding,
        "documents": [{"id": key, "name": ISSUED[key][0]} for key in ISSUED],
    }


def relieving_letter(case_id: str) -> bytes:
    case_meta, emp = _context(case_id)
    st = _styles()
    name = emp.get("name") or case_meta.get("employee_name") or "the employee"
    return _render(
        ISSUED["relieving-letter"][1],
        f"{case_meta.get('case_id')} · issued to {name}",
        [
            _facts_table([
                ("Name", name),
                ("Employee ID", emp.get("id")),
                ("Designation", emp.get("role")),
                ("Department", emp.get("department")),
                ("Date of joining", emp.get("join_date")),
                ("Last working day", case_meta.get("last_working_day")),
            ]),
            Spacer(1, 16),
            Paragraph(
                f"This is to confirm that {name} has been relieved from the "
                f"services of {COMPANY} with effect from the close of business "
                f"on {_fmt(case_meta.get('last_working_day'))}.", st["body"]),
            Paragraph(
                "All clearance formalities recorded against this exit — IT, "
                "Finance, HR, knowledge transfer and manager sign-off — have "
                "been completed. Company assets issued to them have been "
                "accounted for and system access has been revoked.", st["body"]),
            Paragraph(
                f"We thank {name} for their contribution and wish them well.",
                st["body"]),
        ])


def experience_letter(case_id: str) -> bytes:
    case_meta, emp = _context(case_id)
    st = _styles()
    name = emp.get("name") or case_meta.get("employee_name") or "the employee"
    tenure = emp.get("tenure_years")
    return _render(
        ISSUED["experience-letter"][1],
        f"To whom it may concern · {case_meta.get('case_id')}",
        [
            _facts_table([
                ("Name", name),
                ("Designation at exit", emp.get("role")),
                ("Department", emp.get("department")),
                ("From", emp.get("join_date")),
                ("To", case_meta.get("last_working_day")),
                ("Length of service", f"{tenure} years" if tenure is not None else None),
                ("Location", emp.get("location")),
            ]),
            Spacer(1, 16),
            Paragraph(
                f"This is to certify that {name} was employed with {COMPANY} as "
                f"{_fmt(emp.get('role'))} in the {_fmt(emp.get('department'))} "
                f"department from {_fmt(emp.get('join_date'))} to "
                f"{_fmt(case_meta.get('last_working_day'))}.", st["body"]),
            # Nothing about conduct or performance. The record holds a
            # performance rating, and turning an internal number into a
            # sentence on a reference letter is a judgement the company has not
            # made and this system is not entitled to make for it.
            Paragraph(
                "This certificate is issued at their request and states the "
                "period and capacity of employment only.", st["body"]),
        ])


def settlement_statement(case_id: str) -> bytes:
    case_meta, emp = _context(case_id)
    st = _styles()
    name = emp.get("name") or case_meta.get("employee_name") or "the employee"

    assets = asset_status(case_id)
    returned = [a["asset"] for a in assets.get("assets", []) if a["state"] == "returned"]
    written_off = assets.get("written_off") or []

    stages = {str(s.get("name")): str(s.get("status", ""))
              for s in (case_meta.get("stages") or []) if isinstance(s, dict)}

    blocks: list[Any] = [
        _facts_table([
            ("Name", name),
            ("Employee ID", emp.get("id")),
            ("Last working day", case_meta.get("last_working_day")),
            ("Finance clearance", stages.get("Finance Clearance")),
            ("HR clearance", stages.get("HR Clearance")),
        ]),
        Spacer(1, 14),
        Paragraph(
            "Assets issued to the employee, as recorded by IT at the time of "
            "handover:", st["body"]),
        _facts_table(
            [(a, "Returned") for a in returned]
            + [(a, "Not returned — recoverable from settlement") for a in written_off]
            or [("No assets on record", "")]),
        Spacer(1, 14),
    ]

    if written_off:
        blocks.append(Paragraph(
            f"{len(written_off)} item{'s' if len(written_off) != 1 else ''} "
            "above was not returned. Its value is recoverable against the final "
            "settlement; the amount is determined by payroll from the asset "
            "register, not by this document.", st["body"]))

    blocks.append(Paragraph(
        "Finance clearance confirms that no dues were outstanding against the "
        "employee at the time of release, other than any recovery noted above. "
        "Settlement amounts, notice-period adjustments, leave encashment and "
        "statutory deductions are computed by payroll and issued separately; "
        "this statement records the clearance position only.", st["body"]))

    return _render(ISSUED["settlement-statement"][1],
                   f"{case_meta.get('case_id')} · {name}", blocks)


GENERATORS = {
    "relieving-letter": relieving_letter,
    "experience-letter": experience_letter,
    "settlement-statement": settlement_statement,
}


def generate(case_id: str, document_id: str) -> tuple[bytes, str]:
    """(pdf bytes, filename). Raises LookupError for an unknown document."""
    if document_id not in GENERATORS:
        raise LookupError(f"Unknown document '{document_id}'.")
    state = readiness(case_id)
    if not state["ready"]:
        raise PermissionError(
            "These are issued once every clearance is complete. Still open: "
            + ", ".join(state["outstanding"]) + ".")
    _, emp = _context(case_id)
    who = str(emp.get("name") or case_id).replace(" ", "-")
    stem = ISSUED[document_id][0].replace(" ", "-").lower()
    return GENERATORS[document_id](case_id), f"{stem}-{who}.pdf"
